-- ============================================================================
-- Package: ANALYSIS_PKG (EscrowAnalysisDB.runEscrowAnalysis stored procedure)
-- ============================================================================
CREATE OR REPLACE PACKAGE ANALYSIS_PKG AS
    -- Run automated analysis assessment
    -- Called by: EscrowAnalysisDB.jca - operation="runEscrowAnalysis"
    -- InteractionSpec: oracle.tip.adapter.db.DBStoredProcedureInteractionSpec
    PROCEDURE RUN_ESCROW_ANALYSIS(
        p_escrow_account_id        IN  VARCHAR2,
        p_payment_score   IN  NUMBER,
        p_shortage_ratio      IN  NUMBER,
        p_monthly_escrow_payment IN  NUMBER,
        p_annual_disbursement    IN  NUMBER,
        p_analysis_score     OUT NUMBER,
        p_recommendation OUT VARCHAR2,
        p_analysis_notes          OUT VARCHAR2
    );
END ANALYSIS_PKG;
/

CREATE OR REPLACE PACKAGE BODY ANALYSIS_PKG AS
    PROCEDURE RUN_ESCROW_ANALYSIS(
        p_escrow_account_id        IN  VARCHAR2,
        p_payment_score   IN  NUMBER,
        p_shortage_ratio      IN  NUMBER,
        p_monthly_escrow_payment IN  NUMBER,
        p_annual_disbursement    IN  NUMBER,
        p_analysis_score     OUT NUMBER,
        p_recommendation OUT VARCHAR2,
        p_analysis_notes          OUT VARCHAR2
    ) IS
        v_dti_ratio NUMBER;
        v_score NUMBER := 0;
    BEGIN
        -- Calculate DTI (assuming monthly escrow payment is ~0.6% of escrow amount)
        v_dti_ratio := ((p_annual_disbursement * 0.006) / p_monthly_escrow_payment) * 100;

        -- Score calculation based on payment standing score (0-400 points)
        IF p_payment_score >= 750 THEN
            v_score := v_score + 400;
        ELSIF p_payment_score >= 700 THEN
            v_score := v_score + 300;
        ELSIF p_payment_score >= 650 THEN
            v_score := v_score + 200;
        ELSIF p_payment_score >= 600 THEN
            v_score := v_score + 100;
        END IF;

        -- Score based on shortage (0-300 points)
        IF p_shortage_ratio <= 80 THEN
            v_score := v_score + 300;
        ELSIF p_shortage_ratio <= 90 THEN
            v_score := v_score + 200;
        ELSIF p_shortage_ratio <= 95 THEN
            v_score := v_score + 100;
        END IF;

        -- Score based on DTI (0-300 points)
        IF v_dti_ratio <= 28 THEN
            v_score := v_score + 300;
        ELSIF v_dti_ratio <= 36 THEN
            v_score := v_score + 200;
        ELSIF v_dti_ratio <= 43 THEN
            v_score := v_score + 100;
        END IF;

        p_analysis_score := v_score;

        -- Generate recommendation
        IF v_score >= 800 THEN
            p_recommendation := 'APPROVED';
            p_analysis_notes := 'Excellent analysis profile. Auto-approved.';
        ELSIF v_score >= 600 THEN
            p_recommendation := 'APPROVED';
            p_analysis_notes := 'Good analysis profile. Approved with standard terms.';
        ELSIF v_score >= 400 THEN
            p_recommendation := 'MANUAL_REVIEW';
            p_analysis_notes := 'Moderate analysis. Requires manual escrow analysis review.';
        ELSE
            p_recommendation := 'REJECTED';
            p_analysis_notes := 'High analysis profile. Does not meet minimum requirements.';
        END IF;

    END RUN_ESCROW_ANALYSIS;
END ANALYSIS_PKG;
/


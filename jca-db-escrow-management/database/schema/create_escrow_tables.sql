-- ============================================================================
-- Package: ESCROW_PKG (EscrowAccountDB.calculateShortage stored procedure)
-- ============================================================================
CREATE OR REPLACE PACKAGE ESCROW_PKG AS
    -- Calculate Escrow-to-Value ratio
    -- Called by: EscrowAccountDB.jca - operation="calculateShortage"
    -- InteractionSpec: oracle.tip.adapter.db.DBStoredProcedureInteractionSpec
    PROCEDURE CALCULATE_SHORTAGE(
        p_annual_disbursement    IN  NUMBER,
        p_escrow_balance IN  NUMBER,
        p_shortage_ratio      OUT NUMBER
    );
END ESCROW_PKG;
/

CREATE OR REPLACE PACKAGE BODY ESCROW_PKG AS
    PROCEDURE CALCULATE_SHORTAGE(
        p_annual_disbursement    IN  NUMBER,
        p_escrow_balance IN  NUMBER,
        p_shortage_ratio      OUT NUMBER
    ) IS
    BEGIN
        IF p_escrow_balance > 0 THEN
            p_shortage_ratio := ROUND((p_annual_disbursement / p_escrow_balance) * 100, 2);
        ELSE
            p_shortage_ratio := 0;
        END IF;
    END CALCULATE_SHORTAGE;
END ESCROW_PKG;
/

